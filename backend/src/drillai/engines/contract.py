class PortSpec(BaseModel):
    model_config = ConfigDict(frozen=True)
    name: str
    description: str = ""
    required: bool = True

    def validate_known(self) -> None:
        if self.name not in PORT_TYPES:
            raise EngineInputInvalid(f"unknown context port {self.name!r}")


class EngineSpec(BaseModel):
    """Static, inspectable description of an engine."""

    model_config = ConfigDict(frozen=True)
    key: str
    name: str
    version: str
    domain_pack: str
    category: str
    summary: str
    inputs_model: type[BaseModel]
    outputs_model: type[BaseModel]
    consumes: tuple[str, ...] = ()
    produces: tuple[str, ...] = ()
    parameters: dict[str, dict[str, Any]] = Field(default_factory=dict)
    assumptions: tuple[str, ...] = ()
    limitations: tuple[str, ...] = ()
    references: tuple[str, ...] = ()
    tags: tuple[str, ...] = ()
    deterministic: bool = True
    action_level: ActionLevel = "L1"
    requires_well_context: bool = False
    validation_status: str = Field(
        default="verified_against_reference",
        description="verified_against_reference | formula_derived | needs_field_validation",
    )

    def describe(self) -> dict[str, Any]:
        """UI/registry representation, including JSON schemas and declared units."""
        return {
            "key": self.key,
            "name": self.name,
            "version": self.version,
            "domain_pack": self.domain_pack,
            "category": self.category,
            "summary": self.summary,
            "consumes": list(self.consumes),
            "produces": list(self.produces),
            "parameters": self.parameters,
            "assumptions": list(self.assumptions),
            "limitations": list(self.limitations),
            "references": list(self.references),
            "tags": list(self.tags),
            "deterministic": self.deterministic,
            "action_level": self.action_level,
            "requires_well_context": self.requires_well_context,
            "validation_status": self.validation_status,
            "input_schema": self.inputs_model.model_json_schema(),
            "output_schema": self.outputs_model.model_json_schema(),
        }


class ConstraintViolation(BaseModel):
    model_config = ConfigDict(frozen=True)
    name: str
    message: str
    severity: Literal["info", "warning", "error"] = "warning"
    limit: float | None = None
    actual: float | None = None
    unit: str | None = None
    source: str | None = None


class EngineResult(BaseModel):
    """Outcome envelope returned by every engine execution."""

    outputs: BaseModel
    warnings: list[str] = Field(default_factory=list)
    violations: list[ConstraintViolation] = Field(default_factory=list)
    assumptions_applied: list[str] = Field(default_factory=list)
    extra: dict[str, Any] = Field(default_factory=dict)

    @property
    def is_feasible(self) -> bool:
        return not any(v.severity == "error" for v in self.violations)


@runtime_checkable
class Engine(Protocol):
    spec: EngineSpec

    def run(self, inputs: BaseModel) -> EngineResult: ...


class FunctionEngine:
    """Adapter turning a plain function into an engine."""

    def __init__(
        self,
        spec: EngineSpec,
        fn: Callable[[BaseModel], EngineResult],
    ) -> None:
        self.spec = spec
        self._fn = fn

    def run(self, inputs: BaseModel) -> EngineResult:
        if not isinstance(inputs, self.spec.inputs_model):
            raise EngineInputInvalid(
                f"{self.spec.key} expects {self.spec.inputs_model.__name__}, got {type(inputs).__name__}"
            )
        return self._fn(inputs)


def unit_meta(dimension: Dimension | str) -> dict[str, str]:
    value = dimension.value if isinstance(dimension, Dimension) else dimension
    return {"dimension": value}
