"""Engineering engine contract.

An *engineering engine* is a deterministic, versioned, inspectable calculation. It is a
different concept from a tool, a skill, an agent or a workflow node (ADR-0002):

* it has **typed inputs and outputs** whose units are declared in the schema;
* it declares the **context ports** it consumes and produces, which is what lets the
  platform compute change impact and the order in which engines must re-run;
* it declares its **assumptions, limitations and references** so that a result can be
  defended and, where necessary, challenged;
* it is **deterministic**: same inputs (canonical SI) + same version → same outputs hash;
* it never calls an LLM. Numeric engineering answers are not generated by language models.

Engines are invoked identically from the API, a workflow node, an agent tool, an
optimizer or a scheduled job, and every execution is persisted as an ``EngineRun`` with
input/output hashes (reproducibility) and optional evidence links.
"""

